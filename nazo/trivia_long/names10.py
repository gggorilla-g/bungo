def L(say, face="通常", img=None, fx=None, up=False, hold=0.0, z=None, **kw):
    d = {"say": say, "face": face}
    if img:
        sp = img.rsplit("_", 1)[0]
        d["img"] = f"{P}/{sp}/{img}.jpg"
    if fx:
        d["fx"] = fx if isinstance(fx, list) else [fx]
    if up:
        d["up"] = True
    if hold:
        d["hold"] = hold
    if z:
        d["z"] = z
    d.update(kw)
    return d


def S(text, at=0.25, y=0.5, size=150, color=None, x=0.5):
    f = {"type": "stamp", "text": text, "at": at, "y": y, "size": size, "x": x}
    if color:
        f["color"] = color
    return f


def C(to, unit, label, at=0.2, dec=0):
    return {"type": "count", "to": to, "unit": unit, "label": label, "at": at, "dec": dec}


def B(items, unit, at=0.2):
    return {"type": "bars", "items": items, "unit": unit, "at": at}


